function parseInstaHandle(input) {
  if (!input) return "";
  let s = input.trim();
  s = s.replace(/^https?:\/\/(www\.)?instagram\.com\//i, "");
  s = s.split(/[/?#]/)[0];
  s = s.replace(/^@/, "");
  return s.trim();
}


